// Regenerates src/features/lab/editor/monacoCore.ts from the installed monaco-editor version.
const fs = require('fs')
const main = fs.readFileSync('node_modules/monaco-editor/esm/vs/editor/editor.main.js', 'utf8')
const lines = main.split('\n').filter((l) => l.startsWith("import '"))
const keep = lines.filter((l) => !l.includes('languages/definitions') && !l.includes('languages/features') && !l.includes('monaco-lsp-client'))
const rewritten = keep.map((l) => {
  const p = /^import '(.+)';$/.exec(l)[1]
  return `import '${p.startsWith('./') ? 'monaco-esm/editor/' + p.slice(2) : 'monaco-esm/' + p.slice(3)}'`
})
const langs = ['javascript', 'typescript', 'markdown', 'yaml', 'html', 'css', 'shell', 'ini', 'dockerfile', 'xml']
fs.writeFileSync(
  'src/features/lab/editor/monacoCore.ts',
  ['// GENERATED by scripts/gen-monaco-core.cjs: Monaco editor features + the languages labs need, without the 80 other grammars.', "export * from 'monaco-esm/editor/editor.api.js'", ...rewritten, ...langs.map((l) => `import 'monaco-esm/languages/definitions/${l}/register.js'`), "import 'monaco-esm/languages/features/json/register.js'", ''].join('\n'),
)
